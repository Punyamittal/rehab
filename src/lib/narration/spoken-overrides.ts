export function applySpokenOverrides(language: Language, text: string): string {
  const replacements = SPOKEN_REPLACEMENTS[language];
  if (!replacements?.length || !text.trim()) return text;

  let output = text;
  for (const [from, to] of replacements) {
    output = output.split(from).join(to);
  }
  return output;
}

